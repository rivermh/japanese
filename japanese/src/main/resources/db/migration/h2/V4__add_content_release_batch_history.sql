create table content_release_batches (
    id bigint generated by default as identity,
    reviewer_id bigint not null,
    status varchar(32) not null,
    mode varchar(48) not null,
    gate_version varchar(40) not null,
    preview_digest varchar(64) not null,
    execution_note varchar(1000) not null,
    target_count integer not null,
    success_count integer not null,
    releasable_count integer not null,
    manual_override_count integer not null,
    blocked_count integer not null,
    created_at timestamp(6) with time zone not null,
    executed_at timestamp(6) with time zone not null,
    rolled_back_at timestamp(6) with time zone,
    rollback_reason varchar(1000),
    primary key (id),
    constraint uk_content_release_batch_preview unique (gate_version, preview_digest),
    constraint fk_content_release_batch_reviewer foreign key (reviewer_id) references user_accounts(id)
);

create table content_release_batch_items (
    id bigint generated by default as identity,
    batch_id bigint not null,
    content_item_id bigint not null,
    position integer not null,
    previous_review_status varchar(20) not null,
    previous_published boolean not null,
    resulting_review_status varchar(20) not null,
    resulting_published boolean not null,
    release_decision varchar(32) not null,
    issue_codes varchar(4000) not null,
    manual_override_issue_codes varchar(4000),
    override_reason varchar(1000),
    source_ref_snapshot varchar(160),
    source_rights_status_snapshot varchar(32),
    success boolean not null,
    primary key (id),
    constraint uk_release_batch_position unique (batch_id, position),
    constraint uk_release_batch_content unique (batch_id, content_item_id),
    constraint fk_release_batch_item_batch foreign key (batch_id) references content_release_batches(id),
    constraint fk_release_batch_item_content foreign key (content_item_id) references content_items(id)
);
